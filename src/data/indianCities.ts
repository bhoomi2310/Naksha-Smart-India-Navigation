// Flattened list for autocomplete
export const allLocations = indianCities.flatMap(city => 
  city.locations.map(location => ({
    value: `${location}, ${city.city}`,
    city: city.city,
    location: location
  }))
);

// Get locations for a specific city
export const getLocationsByCity = (cityName: string) => {
  const city = indianCities.find(c => c.city.toLowerCase() === cityName.toLowerCase());
  return city ? city.locations.map(loc => `${loc}, ${city.city}`) : [];
};

// Search locations
export const searchLocations = (query: string) => {
  const lowerQuery = query.toLowerCase();
  return allLocations.filter(item => 
    item.value.toLowerCase().includes(lowerQuery) ||
    item.city.toLowerCase().includes(lowerQuery) ||
    item.location.toLowerCase().includes(lowerQuery)
  ).slice(0, 10); // Limit to 10 results
};
